def M(id, gloss, by, note=''):
    """A meaning: id, gloss and who proposes it (list of (who, where))."""
    return {'id': id, 'gloss': gloss, 'proposed_by': [{'who': w, 'where': r} for w, r in by], 'note': note}


def O(line, words, entry, en, p15=None, p06=None, lef=None, milik=None, link='explicit',
      proposer=None, link_note='', membership='certain', condition='', also=(), note='',
      reading_status='agreed', number=None):
    """An occurrence in the text shown (data/scroll-text.js)."""
    eds = {}
    for key, value in (('puech2015', p15), ('puech2006', p06), ('lefkovits2000', lef), ('milik', milik)):
        if value is not None:
            eds[key] = value
    return {'line': line, 'words': list(words), 'entry': entry, 'en': en, 'editions': eds,
            'link': link, 'proposer': proposer, 'link_note': link_note,
            'membership': membership, 'condition': condition,
            'also': [{'line': l, 'words': list(w)} for l, w in also], 'note': note,
            'reading_status': reading_status, 'number': number}


def P(entry, basis, who, where):
    """A proposed association: the entry is linked to the expression's referent by an editor or the project."""
    return {'entry': entry, 'basis': basis, 'proposer': who, 'where': where}


def E(id, label, category, hebrew, meanings, occurrences, search=(), exclude=(), proposed=(), note='', uniform=True):
    """uniform=False marks a rule that may differ from line to line (e.g. decided by grammatical gender)."""
    return {'id': id, 'label': label, 'category': category, 'hebrew': hebrew,
            'meanings': meanings, 'occurrences': occurrences, 'search': list(search),
            'exclude': [{'line': l, 'word': w, 'why': y} for l, w, y in exclude],
            'proposed': list(proposed), 'note': note, 'uniform': uniform}


