def AF(entry, field, quote, reqs, note=''):
    kind = 'atlas_title' if field == 'title' else 'atlas_text'
    return REC(f'atlas:{entry}:{field}', kind, ATLAS, {'entry': entry, 'field': field}, quote, reqs, entry=entry, note=note)


def AC(entry, place, status, reqs, note=''):
    rec = REC(f'atlas:{entry}:{place}', 'atlas_candidate', ATLAS, {'entry': entry, 'placeId': place}, status, reqs,
              entry=entry, place=place, status=status, group=f'atlas:{entry}', note=note)
    rec['option'] = place
    return rec


def RG(rid, entry, place, field, quote, reqs, note='', open_=False, path=REG):
    rec = REC(f'registry:{rid}:{field}', 'registry', path, {'record': rid, 'field': field}, quote, reqs, entry=entry, place=place,
              group=f'registry:{entry}', note=note, open_=open_)
    rec['option'] = rid
    return rec


def TL(line, quote, reqs, entry=None, note=''):
    return REC(f'translation:{line}:{reqs[0]["expr"]}', 'translation', TR, {'line': line}, quote, reqs, entry=entry, note=note)


def FILE(id, kind, path, quote, reqs, entry=None, group=None, option=None, note=''):
    rec = REC(id, kind, path, {}, quote, reqs, entry=entry, group=group, note=note)
    if group:
        rec['option'] = option
    return rec


